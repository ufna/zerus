#pragma once

#include "TerminalBackend.h"

#include <QString>
#include <QVector>

// «Копировать, а не открывать»: клик по сессии кладёт команду подключения в буфер обмена,
// а пользователь сам вставляет её в ту вкладку, которая ему нужна.
//
// Это не костыль, а обход сразу двух компромиссов, в которые упираются оба настоящих
// бэкенда: на Linux Konsole не даёт вкладку, пока не включён security-sensitive D-Bus API
// (то есть пока любой процесс на сессионной шине не получит право печатать в чужие
// вкладки), а на маке Terminal.app вкладку не умеет в принципе -- и единственный
// кандидат, который умел бы (Tabby), на маке недоступен и из трея удалён, см. врезку в
// MacBackend.h. Вставка в уже открытую вкладку не требует ни того, ни другого -- поэтому
// режим единственный из всех платформонезависимый.
//
// canRaise() остаётся false: поднимать нечего, мы ничего не открываем.
class ClipboardBackend : public TerminalBackend {
public:
    // Способ положить текст в буфер. Порядок попыток задаёт methodChain().
    enum class Method {
        // org.kde.klipper /klipper setClipboardContents(s). Главный путь на Plasma и
        // единственный, который на Wayland работает НАДЁЖНО: протокол требует от клиента
        // serial от собственного недавнего ввода, чтобы захватить selection, а у трея нет
        // ни своей поверхности (меню рисует plasmashell по DBusMenu), ни ввода в неё --
        // тот же корень, из-за которого не работает подъём окна в KonsoleBackend::raiseTty.
        // klipper -- часть plasmashell, у него serial свой и есть всегда.
        Klipper,
        // wl-copy(1) из wl-clipboard. Отдельный процесс со своей поверхностью-донором;
        // нужен там, где Wayland есть, а klipper'а нет (sway, Hyprland, GNOME).
        WlCopy,
        // QGuiApplication::clipboard(). На X11 и на маке этого достаточно; на Wayland это
        // именно тот путь, который может тихо не сработать, поэтому он последний.
        QtClipboard,
    };

    // Единственное, от чего зависит цепочка. Параметр, а не Q_OS_*-макрос внутри open():
    // так выбор способа остаётся чистой функцией и цепочка ОБЕИХ платформ проверяется
    // тестом на любой из них -- в отличие от #ifdef, который на своей машине проверить
    // нечем.
    enum class Platform { Linux, Mac };

    bool open(const QString &command, QString *error) override;
    QString takeAdvisory() override;
    QString advisoryTitle() const override;

    // --- чистые части: тестируются без десктопа, D-Bus и буфера обмена ---

    // Способы для платформы в порядке предпочтения. Непустой всегда: даже если все
    // откажут, отказать должен open() с внятным текстом, а не пустой цикл.
    static QVector<Method> methodChain(Platform platform);
    // Единственное место во всём классе, где вообще есть #ifdef по платформе.
    static Platform currentPlatform();
    // Имя способа для текста ошибки -- пользователь должен понимать, что именно не вышло.
    static QString methodName(Method m);
    // Годится ли команда к копированию. Отдельно от open(), потому что проверка чистая, а
    // цена ошибки высокая: перевод строки внутри команды превращает «вставлю и посмотрю»
    // в «вставилось и выполнилось» -- ровно в той вкладке, где, возможно, работает агент.
    static bool isCopyable(const QString &command, QString *error);
    // Тело уведомления: сама команда, при неадекватной длине -- с многоточием В СЕРЕДИНЕ.
    // Обрезать хвост нельзя: именно там имя сессии, то есть единственное, чем одна
    // команда отличается от другой; начало ("hgs @host a") -- тоже не мусор, оно говорит,
    // на каком боксе сессия. Порог заведомо выше всего, что трей строит в жизни (например,
    // "hgs @mac a claude/sample_web_application-front"):
    // это предохранитель от патологического имени каталога, а не штатная обрезка.
    static QString notificationText(const QString &command);

private:
    // Заполняется на КАЖДЫЙ успешный open() (в отличие от KonsoleBackend/MacBackend, где
    // advisory -- одноразовое объяснение расхождения за прогон): здесь это не пояснение,
    // а подтверждение действия, которого пользователь иначе не увидит вовсе -- ничего же
    // не открылось. Забирается ровно один раз, как требует контракт takeAdvisory().
    QString m_advisory;
};
