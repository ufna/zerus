// @vitest-environment happy-dom
import { afterEach, describe, expect, it, vi } from "vitest";
import { createComponent, For } from "solid-js";
import { render } from "solid-js/web";
import fixture from "./fixtures/agent-team-views.json";
import type { TeamList, TeamView } from "../../store/teams";
import { applyBatch, toSession } from "../../store/catalog";
import { agentTeamIndex, agentTeamProjects, agentTeamSession } from "./agent-teams";
import { groupRows, type Row } from "./group-rows";
import { SessionCard, CompactCard } from "./SessionCard";
import { AgentTeamHeading } from "./AgentTeamHeading";
import { sessionRowName } from "./SessionList";
import { listRows, rowHeight } from "./model";
import { teams } from "../../store/teams";
import { applyMachines } from "../../store/machines";
import { emptyBatch } from "../../types";
import type { Session } from "./types";

vi.hoisted(() => vi.stubGlobal("location", new URL("http://localhost/")));
vi.mock("../../store/catalog", async (original) => ({ ...await original<object>(), computerFresh: () => true, computerOffline: () => false }));

// Generated by the CLI's ops writers, then serialized by the core's own view
// types. No Teams result rows are handwritten here. Session UI inputs below
// are synthetic, deliberately unrelated to the team's session names.
const { list, team } = fixture as unknown as { list: TeamList; team: TeamView };
const machine = "00000000-0000-4000-8000-0000000000aa";
function sessions(): Session[] {
  return team.members.filter((m) => m.session).map((m, i) => toSession("", `run:${m.id}`, {
    name: `codex/unrelated/${3 - i}`, title: `Session ${m.id}`, agent: "codex", run_id: `run-${m.id}`,
    launch_id: m.session!.session_id.slice("launch_id:".length), conversation_id: m.lead ? "lead-conversation" : "",
    status: "ready", caption: m.lead ? "Ready" : "Status unknown", state: "running", process_state: "running",
  }));
}
function rows(input = sessions().reverse(), availability: { value: boolean | undefined } = { value: true }, detail: TeamView | undefined = undefined): Row[] {
  const index = agentTeamIndex(availability.value, list.teams, detail, input, () => machine);
  return groupRows({ grouping: { loaded: false } as never, members: new Map([["project", input]]), agentTeams: index,
    visible: () => true, online: () => true, projects: [], expanded: () => false, compact: () => false });
}
let dispose: (() => void) | undefined;
afterEach(() => { dispose?.(); dispose = undefined; document.body.innerHTML = ""; });
function show(rows: Row[], compact = false) {
  const host = document.createElement("div"); document.body.append(host);
  dispose = render(() => createComponent(For, { each: rows, children: (row: Row) => {
    if (row.type === "agent-team") return createComponent(AgentTeamHeading, { name: row.name });
    if (row.type !== "card") return null;
    return compact ? createComponent(CompactCard, { session: row.session, agentTeamRole: row.agentTeamRole, selected: false, onExpand() {} })
      : createComponent(SessionCard, { session: row.session, agentTeamRole: row.agentTeamRole, selected: false, expandable: false, expanded: false, onToggleChildren() {} });
  } }), host);
  return host;
}

describe("Agent Teams in Sessions", () => {
  it("feeds the followed store and catalog into the production list model, then turns preview off", () => {
    const ss = sessions();
    applyMachines({ ...emptyBatch(), machines: [{ computer: "", machine: { machine_id: machine } as never }] });
    applyBatch({ ...emptyBatch(), upserts: ss.map((s) => ({ computer: "", key: s.catalogKey, row: {
      name: s.name, title: s.title, launch_id: s.launchId, run_id: s.runId, conversation_id: s.conversationId ?? "",
      status: "ready", caption: s.caption, state: "running", process_state: "running", agent: "codex",
    } })) });
    teams.apply([{ computer: "", key: "list", kind: "list", payload: list }]);
    expect(listRows().filter((r) => r.type === "agent-team")).toHaveLength(1);
    expect(listRows().filter((r) => r.type === "card").map((r) => r.agentTeamRole)).toEqual(["lead", "developer", "developer", "reviewer"]);
    teams.apply([{ computer: "", key: "list", kind: "failed", payload: { code: "teams_inactive", message: "off" } }]);
    expect(listRows().some((r) => r.type === "agent-team")).toBe(false);
    expect(listRows().filter((r) => r.type === "card").every((r) => !r.agentTeamRole)).toBe(true);
  });

  it("renders the real team's name, lead first, members ordered by role and member id", () => {
    const result = rows();
    expect(result[0]).toMatchObject({ type: "agent-team", name: "Fixes" });
    expect(result.filter((r) => r.type === "card").map((r) => r.session.title)).toEqual(["Session lead", "Session m1", "Session m2", "Session m3"]);
    const host = show(result);
    expect(host.querySelector('[role="heading"]')?.textContent).toBe("Fixes");
    expect([...host.querySelectorAll(".sc-team-role")].map((el) => el.textContent)).toEqual(["lead", "developer", "developer", "reviewer"]);
    expect(host.textContent).toContain("Waiting for a task");
    expect(host.textContent).not.toContain("Status unknown");
    expect(sessionRowName(result[0])).toBe("Fixes");
    expect(rowHeight(result[0])).toBe(40);
  });

  it("shows the role and waiting caption in compact rows too", () => {
    const host = show(rows(), true);
    expect(host.querySelectorAll(".sc-team-role")).toHaveLength(4);
    expect(host.textContent).toContain("Waiting for a task");
  });

  it("uses bindings even with unrelated names and never matches a lookalike name", () => {
    const members = sessions();
    const impostor = { ...members[1], key: "impostor", name: "codex/zerus-team-Fixes/team-m1", launchId: "different", runId: "different" };
    const result = rows([impostor, ...members]);
    const plain = result.find((r) => r.type === "card" && r.id === "impostor");
    expect(plain).toMatchObject({ session: { caption: "Status unknown" } });
    expect(plain?.type === "card" ? plain.agentTeamRole : "missing").toBeUndefined();
    expect(result.filter((r) => r.type === "card" && r.agentTeamRole)).toHaveLength(4);
  });

  it("requires the machine as well as the launch, and falls back to a bound run id", () => {
    const ss = sessions();
    expect(agentTeamIndex(true, list.teams, team, ss, () => "another-machine").size).toBe(0);
    const member = list.teams[0].member_sessions![1];
    const summaries = structuredClone(list.teams);
    summaries[0].member_sessions![1].session_id = "run_id:run-m1";
    const noLaunch = ss.map((s) => s.title === "Session m1" ? { ...s, launchId: undefined } : s);
    expect(agentTeamIndex(true, summaries, undefined, noLaunch, () => member.machine).get(noLaunch[1].key)?.member).toBe("m1");
  });

  it("reads role details only from a view with the same team, member and binding", () => {
    const ss = sessions();
    const view = structuredClone(team);
    view.members[1].role = "quality";
    expect(agentTeamIndex(true, list.teams, view, ss, () => machine).get(ss[1].key)?.role).toBe("quality");
    view.members[1].session!.session_id = "launch_id:another";
    expect(agentTeamIndex(true, list.teams, view, ss, () => machine).get(ss[1].key)?.role).toBe("developer");
  });

  it.each([false, undefined])("leaves preview %s sessions, order and status unchanged", (available) => {
    const ss = sessions().reverse();
    const result = rows(ss, { value: available });
    expect(result.map((r) => r.id)).toEqual(ss.map((s) => s.key));
    const host = show(result);
    expect(host.querySelector('[role="heading"]')).toBeNull();
    expect(host.querySelector(".sc-team-role")).toBeNull();
    expect(host.textContent).toContain("Status unknown");
    expect(host.textContent).not.toContain("Waiting for a task");
  });

  it("leaves an ordinary live session without a conversation unchanged", () => {
    const s = { ...sessions()[1], key: "ordinary", launchId: "ordinary-launch", runId: "ordinary-run" };
    const result = rows([s]);
    expect(result).toHaveLength(1);
    expect(result[0]).toMatchObject({ session: s });
    expect(agentTeamSession(s, undefined, true)).toBe(s);
    expect(show(result).textContent).toContain("Status unknown");
  });

  it("keeps attention, work, exit, offline and existing-conversation states", () => {
    const s = sessions()[1], member = agentTeamIndex(true, list.teams, undefined, [s], () => machine).get(s.key)!;
    for (const update of [{ status: "working" }, { status: "attention" }, { backgroundJobs: 1 }, { draft: true }, { processState: "exited" }, { state: "paused" }, { conversationId: "first-task" }] as Partial<Session>[]) {
      const changed = { ...s, ...update };
      expect(agentTeamSession(changed, member, true)).toBe(changed);
    }
    expect(agentTeamSession(s, member, false)).toBe(s);
    expect(agentTeamSession(sessions()[0], { ...member, lead: true }, true).caption).toBe("Ready");
  });

  it("keeps members together in the lead's project without changing assignments", () => {
    const ss = sessions();
    const index = agentTeamIndex(true, list.teams, team, ss, () => machine);
    const assigned = new Map([["other", ss.slice(1)], ["lead-project", [ss[0]]]]);
    const grouped = agentTeamProjects(assigned, index);
    expect(grouped.get("lead-project")).toHaveLength(4);
    expect(assigned.get("other")).toHaveLength(3);
    expect(agentTeamProjects(assigned, new Map())).toBe(assigned);
  });

  it("does not establish membership from a conflicting binding or inactive team", () => {
    const ss = sessions();
    expect(agentTeamIndex(true, [...list.teams, ...list.teams], team, ss, () => machine).size).toBe(0);
    const stopped = list.teams.map((t) => ({ ...t, status: "stopped" }));
    expect(agentTeamIndex(true, stopped, team, ss, () => machine).size).toBe(0);
  });
});
